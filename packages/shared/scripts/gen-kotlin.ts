export interface GenerateKotlinResult {
  kotlin: string;
  warnings: string[];
}

const HEADER = "// GENERATED by packages/shared/scripts/gen-kotlin.ts — do not edit.";

export const KOTLIN_PACKAGE = "dev.optio.core.model";

const ANY = "JsonElement";
const UNKNOWN_RAW = "__unknown__";

