/**
 * gen-kotlin — emit Kotlin (kotlinx.serialization) models from the shared
 * TypeScript protocol types so the Android app (apps/android) and the server
 * share one wire format. The Kotlin twin of gen-swift.ts: both render the
 * declaration model built by gen-model.ts, so type names match the Swift
 * output (`OptioTask`, `WsEvent`, …) and code ported from iOS reads the same.
 *
 *   pnpm --filter @optio/shared gen:kotlin
 *   # writes apps/android/core/model/src/main/kotlin/dev/optio/core/model/SharedTypes.kt
 *
 * Mapping (package dev.optio.core.model):
 *   interface / object type alias   → @Serializable data class (`data object` when it has no fields)
 *   string enum / string-literal union → enum class with its wire value in `raw` and an
 *                                     UNKNOWN fallback (companion = RawEnumSerializer)
 *   numeric enum                    → Int-backed enum class (companion = IntEnumSerializer)
 *   discriminated object union      → sealed interface: named structs implement it, inline
 *                                     variants become nested classes, plus `Unknown(raw)`;
 *                                     a generated DiscriminatedUnionSerializer picks the variant
 *   `X | null`, `x?: X`             → nullable with a `null` default
 *   `Date` → java.time.Instant (FlexibleInstantSerializer), `number` → Double
 *   unknown / any / functions / tuples / anything irregular → JsonElement (+ warning)
 *
 * Wire keys stay the property names when they are identifiers (Kotlin keywords
 * are backticked); other keys get a camelCase name and `@SerialName`. Generic
 * types, classes, functions and consts are skipped, like gen-swift. A file
 * whose Kotlin twin is hand-written opts out with a leading
 * `// gen-kotlin: skip-file` comment. (`// gen-swift: skip-file` only affects
 * Swift: glance.ts is hand-written for ActivityKit on iOS but generated here.)
 *
 * OptioJson, FlexibleInstantSerializer, RawEnum and DiscriminatedUnionSerializer
 * are hand-written beside the output.
 */

